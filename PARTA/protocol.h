// ------------------------- framing constants -------------------------
static const uint16_t QUIZ_MAGIC   = 0x515A;      // 'Q','Z'
static const uint8_t  QUIZ_VERSION = 0x01;
static const uint32_t MAX_PAYLOAD  = 1u << 20;    // 1 MiB hard cap

// ------------------------- message types -----------------------------
enum Messagetype : uint32_t {
    GENRE_REQUEST       = 1,   // C -> S  payload: genre string
    QUESTION_DELIVERY   = 2,   // S -> C  payload: JSON question (no answer)
    ANSWER_SUBMISSION   = 3,   // C -> S  payload: "A".."D"
    RESULT_DELIVERY     = 4,   // S -> C  payload: JSON verdict + score
    LEADERBOARD_REQUEST = 5,   // C -> S  payload: empty
    LEADERBOARD_DELIVERY= 6,   // S -> C  payload: JSON leaderboard
    SESSION_END         = 7,   // both    payload: JSON final summary
    KEEP_ALIVE          = 8,   // S -> C  payload: empty
    ALIVE_OK            = 9,   // C -> S  payload: empty
    USERNAME_SUBMISSION = 10,  // C -> S  payload: username string
    ERROR_MSG           = 11,  // S -> C  payload: JSON {"error": "..."}
    SERVER_INFO         = 12   // S -> C  payload: JSON session parameters
};

// ------------------------- header flags ------------------------------
enum MessageFlag : uint8_t {
    FLAG_NONE       = 0x00,
    FLAG_CACHE_HIT  = 0x01,   // question served from the server-side cache
    FLAG_CACHE_MISS = 0x02    // question was freshly generated by the LLM
};

#pragma pack(push, 1)
struct MessageHeader {
    uint16_t magic;
    uint8_t  version;
    uint8_t  flags;
    uint32_t type;            // host order once returned by recvMessage()
    uint32_t payload_length;  // host order once returned by recvMessage()
};
#pragma pack(pop)

static const size_t HEADER_SIZE = 12;

enum RecvStatus {
    RECV_OK      =  1,
    RECV_CLOSED  =  0,   // orderly shutdown by peer
    RECV_TIMEOUT = -1,   // SO_RCVTIMEO expired before any byte arrived
    RECV_ERROR   = -2,
    RECV_BADMSG  = -3    // bad magic / version / oversized payload
};

