// ------------------------- small utilities ---------------------------
inline string trimCopy(string s) {
    size_t b = s.find_first_not_of(" \t\r\n");
    if (b == string::npos) return "";
    size_t e = s.find_last_not_of(" \t\r\n");
    return s.substr(b, e - b + 1);
}

inline string upperCopy(string s) {
    transform(s.begin(), s.end(), s.begin(), ::toupper);
    return s;
}

inline string lowerCopy(string s) {
    transform(s.begin(), s.end(), s.begin(), ::tolower);
    return s;
}

// "C", " c ", "C) George Washington" -> 'C'  ;  0 when nothing usable
inline char answerLetter(const string& raw) {
    string s = upperCopy(trimCopy(raw));
    for (size_t i = 0; i < s.size(); ++i) {
        if (s[i] >= 'A' && s[i] <= 'D') {
            // reject a letter that is part of a longer word, e.g. "BERLIN"
            bool next_ok = (i + 1 >= s.size()) || !isalpha((unsigned char)s[i + 1]);
            if (next_ok) return s[i];
        }
    }
    return 0;
}

