inline double nowSeconds() {
    struct timeval tv;
    gettimeofday(&tv, nullptr);
    return tv.tv_sec + tv.tv_usec / 1e6;
}

inline string timestampString() {
    struct timeval tv;
    gettimeofday(&tv, nullptr);
    time_t secs = tv.tv_sec;
    struct tm tmv;
    localtime_r(&secs, &tmv);
    char buf[32];
    strftime(buf, sizeof(buf), "%H:%M:%S", &tmv);
    char out[48];
    snprintf(out, sizeof(out), "%s.%03d", buf, (int)(tv.tv_usec / 1000));
    return string(out);
}

inline string peerString(int fd) {
    sockaddr_in addr;
    socklen_t len = sizeof(addr);
    if (getpeername(fd, (sockaddr*)&addr, &len) != 0) return "unknown";
    char ip[INET_ADDRSTRLEN] = {0};
    inet_ntop(AF_INET, &addr.sin_addr, ip, sizeof(ip));
    return string(ip) + ":" + to_string(ntohs(addr.sin_port));
}

// ------------------------- transport helpers -------------------------
// Byte counters so the client can report application level throughput.
struct ByteCounters {
    std::atomic<long long> sent;
    std::atomic<long long> received;
    ByteCounters() : sent(0), received(0) {}
};
inline ByteCounters& counters() { static ByteCounters c; return c; }

inline bool sendAll(int fd, const char* buf, size_t len) {
    size_t off = 0;
    while (off < len) {
        ssize_t n = send(fd, buf + off, len - off, MSG_NOSIGNAL);
        if (n > 0) { off += (size_t)n; continue; }
        if (n < 0 && errno == EINTR) continue;
        if (n < 0 && (errno == EAGAIN || errno == EWOULDBLOCK)) { usleep(2000); continue; }
        return false;
    }
    counters().sent += (long long)len;
    return true;
}

// Header and payload are concatenated and written with a single sendAll()
// so a frame is never split by a concurrent writer on the same socket.
inline bool sendMessage(int fd, Messagetype type, const string& payload,
                        uint8_t flags = FLAG_NONE) {
    if (payload.size() > MAX_PAYLOAD) return false;
    MessageHeader h;
    h.magic          = htons(QUIZ_MAGIC);
    h.version        = QUIZ_VERSION;
    h.flags          = flags;
    h.type           = htonl((uint32_t)type);
    h.payload_length = htonl((uint32_t)payload.size());

    string frame;
    frame.reserve(HEADER_SIZE + payload.size());
    frame.append((const char*)&h, HEADER_SIZE);
    frame.append(payload);
    return sendAll(fd, frame.data(), frame.size());
}

inline bool sendJson(int fd, Messagetype type, const json& j,
                     uint8_t flags = FLAG_NONE) {
    return sendMessage(fd, type, j.dump(), flags);
}

// allow_initial_timeout: return RECV_TIMEOUT when SO_RCVTIMEO fires before
// the first byte of a frame. Once a frame has started we keep waiting so a
// message is never truncated.
inline int recvExactly(int fd, char* buf, size_t len, bool allow_initial_timeout) {
    size_t off = 0;
    int    stalls = 0;
    while (off < len) {
        ssize_t n = recv(fd, buf + off, len - off, 0);
        if (n > 0) { off += (size_t)n; continue; }
        if (n == 0) return RECV_CLOSED;
        if (errno == EINTR) continue;
        if (errno == EAGAIN || errno == EWOULDBLOCK) {
            if (off == 0 && allow_initial_timeout) return RECV_TIMEOUT;
            if (++stalls > 6) return RECV_ERROR;   // peer died mid-frame
            continue;
        }
        return RECV_ERROR;
    }
    counters().received += (long long)len;
    return RECV_OK;
}

inline int recvMessage(int fd, MessageHeader& out, string& payload,
                       bool allow_timeout = true) {
    MessageHeader raw;
    int st = recvExactly(fd, (char*)&raw, HEADER_SIZE, allow_timeout);
    if (st != RECV_OK) return st;

    if (ntohs(raw.magic) != QUIZ_MAGIC || raw.version != QUIZ_VERSION)
        return RECV_BADMSG;

    uint32_t len = ntohl(raw.payload_length);
    if (len > MAX_PAYLOAD) return RECV_BADMSG;

    payload.assign(len, '\0');
    if (len > 0) {
        st = recvExactly(fd, &payload[0], len, false);
        if (st != RECV_OK) return st;
    }

    out.magic          = QUIZ_MAGIC;
    out.version        = raw.version;
    out.flags          = raw.flags;
    out.type           = ntohl(raw.type);
    out.payload_length = len;
    return RECV_OK;
}

